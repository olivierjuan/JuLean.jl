# JuLean.jl - Lean 4 Export & Certified Artifact Generation

"""
    export_lean_file(filepath::String;
                     fns=collect(keys(SPEC_REGISTRY)),
                     tactics=Dict{Symbol, String}(),
                     imports=["Mathlib.Tactic"],
                     set_options=["linter.unusedVariables false", "linter.unusedTactic false", "linter.unreachableTactic false", "linter.unnecessarySeqFocus false"]) -> String

Exports all registered structures and selected formalized functions into a standalone,
compilable Lean 4 source file.
"""
function export_lean_file(filepath::String;
                         fns=collect(keys(SPEC_REGISTRY)),
                         tactics::Dict{Symbol, String}=Dict{Symbol, String}(),
                         imports::Vector{String}=String["Mathlib.Tactic"],
                         set_options::Vector{String}=String["linter.unusedVariables false", "linter.unusedTactic false", "linter.unreachableTactic false", "linter.unnecessarySeqFocus false"])::String
    lines = String[]

    for imp in imports
        push!(lines, "import $imp")
    end
    push!(lines, "")
    push!(lines, "-- Generated by JuLean.jl")
    push!(lines, "-- Standalone Lean 4 Formal Verification Module")
    push!(lines, "")

    for opt in set_options
        push!(lines, "set_option $opt")
    end
    push!(lines, "")

    # Export all registered structures
    if !isempty(STRUCT_REGISTRY)
        push!(lines, "/-! ### Data Structures -/")
        for (sname, sdecl) in STRUCT_REGISTRY
            push!(lines, to_lean(sdecl))
            push!(lines, "")
        end
    end

    # Export selected functions and theorems
    push!(lines, "/-! ### Definitions & Specifications -/")
    for fn in fns
        if haskey(SPEC_REGISTRY, fn)
            spec = SPEC_REGISTRY[fn]
            tac = get(tactics, fn, "")
            lean_def, lean_thm = transpile_to_lean_decl(spec; tactic=tac)
            push!(lines, to_lean(lean_def))
            push!(lines, "")
            if lean_thm !== nothing
                push!(lines, to_lean(lean_thm))
                push!(lines, "")
            end
        end
    end

    content = join(lines, "\n")
    dir = dirname(abspath(filepath))
    !isdir(dir) && mkpath(dir)
    write(filepath, content)
    return content
end

"""
    verification_summary() -> String

Generates a formatted summary table of all formalized specifications registered in JuLean,
including argument counts, precondition/postcondition/invariant counts, and return types.
"""
function verification_summary()::String
    lines = String[
        "================================================================================",
        " JuLean.jl — Registered Formal Specifications Summary",
        "================================================================================",
        rpad("Function", 25) * rpad("Args", 10) * rpad("Pre", 8) * rpad("Post", 8) * rpad("Inv", 8) * "Return Type",
        "-"^80
    ]

    for (name, spec) in SPEC_REGISTRY
        args_str = string(length(spec.args))
        pre_str = string(length(spec.preconditions))
        post_str = string(length(spec.postconditions))
        inv_str = string(length(spec.invariants))
        ret_str = string(spec.return_type)

        push!(lines, rpad(string(name), 25) * rpad(args_str, 10) * rpad(pre_str, 8) * rpad(post_str, 8) * rpad(inv_str, 8) * ret_str)
    end
    push!(lines, "="^80)
    return join(lines, "\n")
end
